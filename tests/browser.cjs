// Optional: PLAYWRIGHT_MODULE=/path/to/playwright node tests/browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.DEMO_URL || 'http://127.0.0.1:8000');
  await page.locator('#s-doc').filter({hasText:/[0-9]/}).waitFor();
  await page.locator('#question').fill('Who led Bruma del Cobre in 2021?');
  await page.locator('#ask').click();
  await page.waitForFunction(()=>!document.querySelector('#ask').disabled);
  await page.locator('#answer .fact').first().waitFor();
  assert.match(await page.locator('#answer').innerText(), /2020-02-27/);
  await page.locator('#answer .cite').first().click();
  await page.locator('dialog[open] .doc-p.highlight').waitFor();
  await page.locator('dialog .close').click();
  await page.locator('#persona').selectOption('unclassified');
  await page.getByText('No supported relationships were found', {exact:false}).waitFor();
  assert.equal(await page.locator('#answer .fact').count(),0);
  await page.locator('#persona').selectOption('secret');
  await page.waitForFunction(()=>!document.querySelector('#ask').disabled);
  await page.locator('#answer .fact').first().waitFor();
  await page.locator('.chip').first().click();
  await page.waitForFunction(()=>!document.querySelector('#ask').disabled);
  await page.locator('#answer .fact').first().waitFor();
  await page.waitForFunction(()=>!document.querySelector('#answer').classList.contains('loading'));
  assert.match(await page.locator('#answer .fact').first().innerText(), /supported/);
  await page.locator('svg circle').first().waitFor();
  await page.locator('#timeline-tab').click();
  await page.locator('.timeline-item').first().waitFor();
  await page.locator('#graph-tab').click();
  await page.screenshot({ path: '/tmp/kg-dea-desktop.png', fullPage: true });
  await page.getByRole('button',{name:/Extraction scorecard/}).click();
  await page.locator('.metric').first().waitFor();
  assert.equal(await page.locator('.metric').count(),3);
  await page.getByRole('button',{name:/World bible/}).click();
  assert.match(await page.locator('#bible').innerText(),/DRAFT/);
  await page.setViewportSize({ width:390,height:844 });
  await page.getByRole('button',{name:/Investigate/}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile layout overflows');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: search, citations, persona filtering, graph, timeline, scorecard, world bible, mobile layout; no browser errors');
})().catch(e=>{console.error(e);process.exit(1)});
